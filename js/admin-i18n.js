Pivert.initAdminLanguage = root => {
  let lang='fr';try{lang=localStorage.getItem('pivert-admin-language')||'fr';}catch{}
  if(!['fr','en','ru','es'].includes(lang))lang='fr';
  const originals=new WeakMap(),last=new WeakMap(),attrs=new WeakMap();
  const translate=value=>{
    let result=value;
    // Longest phrases first so composed messages and numbered photo labels work.
    for(const row of [...Pivert.adminMessages].sort((a,b)=>b[0].length-a[0].length))result=result.split(row[0]).join(row[{ru:0,fr:1,en:2,es:3}[lang]]);
    return result;
  };
  const switcher=document.createElement('div');switcher.className='admin-interface-languages';switcher.setAttribute('aria-label','Interface language');
  for(const [code,name] of [['fr','Français'],['en','English'],['ru','Русский'],['es','Español']]){
    const button=document.createElement('button');button.type='button';button.textContent=code.toUpperCase();button.title=name;button.dataset.adminLanguage=code;button.onclick=()=>{lang=code;try{localStorage.setItem('pivert-admin-language',lang);}catch{}apply();};switcher.append(button);
  }
  root.querySelector('.admin-top').prepend(switcher);
  function apply(){
    observer.disconnect();document.documentElement.lang=lang;document.title='Pivert — '+translate('Мои объекты');
    const walker=document.createTreeWalker(root,NodeFilter.SHOW_TEXT);let node;
    while(node=walker.nextNode()){
      if(node.parentElement.closest('script,style,textarea,.admin-interface-languages,.admin-listing-info h3,.admin-listing-info p,.admin-listing-meta'))continue;
      if(!originals.has(node)||last.get(node)!==node.textContent)originals.set(node,node.textContent);
      const value=translate(originals.get(node));node.textContent=value;last.set(node,value);
    }
    root.querySelectorAll('[placeholder],[aria-label],[title],img[alt]').forEach(element=>{
      let values=attrs.get(element)||{};
      for(const name of ['placeholder','aria-label','title','alt'])if(element.hasAttribute(name)){
        const current=element.getAttribute(name);if(!values[name]||values[name].last!==current)values[name]={original:current};
        const value=translate(values[name].original);element.setAttribute(name,value);values[name].last=value;
      }attrs.set(element,values);
    });
    switcher.querySelectorAll('button').forEach(button=>button.setAttribute('aria-pressed',button.dataset.adminLanguage===lang));
    observer.observe(root,{childList:true,subtree:true,characterData:true,attributes:true,attributeFilter:['aria-label','title','alt','placeholder']});
  }
  const observer=new MutationObserver(apply);apply();
};
